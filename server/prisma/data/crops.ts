import { REGION_IDS } from '../../src/data/regions.js';

export type StageType = 'ekish' | 'sugorish' | 'ogitlash' | 'himoya' | 'hosil' | 'boshqa';
export interface CareStage {
  day: number; // ekilgan kundan keyin
  type: StageType;
  title: string;
}

const FIELD_REGIONS = REGION_IDS.filter((id) => id !== 'toshkent');

function irrigations(start: number, every: number, count: number): CareStage[] {
  return Array.from({ length: count }, (_, i) => ({
    day: start + i * every,
    type: 'sugorish' as const,
    title: `${i + 1}-sug‘orish`,
  }));
}

